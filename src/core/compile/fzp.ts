/**
 * fzp XML builder (Fritzing 1.0.7 module description).
 *
 * Element order follows the core library and vanepp's community parts: version, author,
 * title, label, date, tags, properties, description, spice, views, connectors, buses.
 * Output is pretty printed with 2-space indentation and LF line endings, and is
 * byte-deterministic for a given (ResolvedPart, RenderContext).
 */
import { layerImage } from "../identity.js";
import type { ResolvedConnector, ResolvedPart } from "../resolve.js";
import { esc } from "../svg.js";
import { layerIdsFor, type RenderContext, type View } from "./types.js";

export const FRITZING_VERSION = "1.0.7";
export const PROJECT_URL = "https://github.com/pmaxhogan/fritzkit";

/** View order inside <views> (the spike parts that passed the checker use this order). */
const FZP_VIEWS: readonly View[] = ["icon", "breadboard", "schematic", "pcb"];

/** Properties fritzkit owns; spec.properties entries with these names are ignored. */
const RESERVED_PROPERTIES = new Set(["family", "variant"]);

/** Tiny line-oriented XML writer: one element per line, 2-space indent. */
class XmlWriter {
  private readonly lines: string[] = [];
  private depth = 0;

  private push(s: string): void {
    this.lines.push("  ".repeat(this.depth) + s);
  }

  open(tag: string, attrs: [string, string][] = []): void {
    this.push(`<${tag}${fmtAttrs(attrs)}>`);
    this.depth++;
  }

  close(tag: string): void {
    this.depth--;
    this.push(`</${tag}>`);
  }

  empty(tag: string, attrs: [string, string][] = []): void {
    this.push(`<${tag}${fmtAttrs(attrs)}/>`);
  }

  /** <tag attrs>escaped text</tag>; text may span several lines. */
  text(tag: string, content: string, attrs: [string, string][] = []): void {
    this.push(`<${tag}${fmtAttrs(attrs)}>${esc(content)}</${tag}>`);
  }

  toString(): string {
    return this.lines.join("\n") + "\n";
  }
}

function fmtAttrs(attrs: [string, string][]): string {
  return attrs.map(([k, v]) => ` ${k}="${esc(v)}"`).join("");
}

/** Normalise CRLF / CR to LF so the fzp stays LF-only even if the spec text is not. */
function lf(s: string): string {
  return s.replace(/\r\n?/g, "\n");
}

/**
 * The fzp <description> text: the spec description, the source URLs, then the
 * generator and licence notice. Plain text (escaped by the writer), LF newlines.
 */
export function fzpDescription(part: ResolvedPart, ctx: RenderContext): string {
  const { spec } = part;
  const year = ctx.date.slice(0, 4);
  const blocks: string[] = [];
  const body = lf(spec.description).trim();
  if (body) blocks.push(body);
  if (spec.sources.length) blocks.push(["Sources:", ...spec.sources].join("\n"));
  blocks.push(
    `Generated by ${ctx.generator} (${PROJECT_URL}). Part artwork and data (c) ${year} ${spec.author}, ` +
      "licensed CC-BY-SA 3.0 like the Fritzing parts library.",
  );
  return blocks.join("\n\n");
}

/** Ordered [name, value] pairs for <properties>: family, variant, then spec.properties by key. */
export function fzpProperties(part: ResolvedPart, ctx: RenderContext): [string, string][] {
  const out: [string, string][] = [
    ["family", ctx.identity.family],
    ["variant", ctx.identity.variant],
  ];
  const keys = Object.keys(part.spec.properties).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  for (const k of keys) {
    if (RESERVED_PROPERTIES.has(k.toLowerCase())) continue;
    out.push([k, part.spec.properties[k] ?? ""]);
  }
  return out.filter(([, v]) => v.trim() !== "");
}

function writeConnector(w: XmlWriter, c: ResolvedConnector): void {
  w.open("connector", [
    ["id", c.fzpId],
    ["type", c.type],
    ["name", c.name],
  ]);
  w.text("description", lf(c.description));
  w.open("views");

  w.open("breadboardView");
  w.empty("p", [
    ["layer", "breadboard"],
    ["svgId", c.svgId],
    c.legId ? ["legId", c.legId] : ["terminalId", c.terminalId],
  ]);
  w.close("breadboardView");

  w.open("schematicView");
  w.empty("p", [
    ["layer", "schematic"],
    ["svgId", c.svgId],
    ["terminalId", c.terminalId],
  ]);
  w.close("schematicView");

  w.open("pcbView");
  if (c.tht)
    w.empty("p", [
      ["layer", "copper0"],
      ["svgId", c.svgId],
    ]);
  w.empty("p", [
    ["layer", "copper1"],
    ["svgId", c.svgId],
  ]);
  w.close("pcbView");

  w.close("views");
  w.close("connector");
}

export function buildFzp(part: ResolvedPart, ctx: RenderContext): string {
  const { spec } = part;
  const { identity } = ctx;
  const w = new XmlWriter();

  w.open("module", [
    ["moduleId", identity.moduleId],
    ["referenceFile", `${identity.moduleId}.fzp`],
    ["fritzingVersion", FRITZING_VERSION],
  ]);

  w.text("version", String(spec.version));
  w.text("author", spec.author);
  w.text("title", spec.title);
  w.text("label", spec.label);
  w.text("date", ctx.date);

  if (spec.tags.length) {
    w.open("tags");
    for (const t of spec.tags) w.text("tag", t);
    w.close("tags");
  } else {
    w.empty("tags");
  }

  w.open("properties");
  for (const [name, value] of fzpProperties(part, ctx)) {
    w.text("property", value, [["name", name]]);
  }
  w.close("properties");

  w.text("description", fzpDescription(part, ctx));

  if (spec.spice) {
    w.open("spice");
    if (spec.spice.model !== undefined && spec.spice.model.trim() !== "") {
      w.text("model", lf(spec.spice.model));
    }
    for (const line of spec.spice.lines) w.text("line", lf(line));
    w.close("spice");
  }

  w.open("views");
  for (const view of FZP_VIEWS) {
    w.open(`${view}View`);
    w.open("layers", [["image", layerImage(identity, view)]]);
    for (const id of layerIdsFor(view, part.hasTht)) w.empty("layer", [["layerId", id]]);
    w.close("layers");
    w.close(`${view}View`);
  }
  w.close("views");

  w.open("connectors");
  for (const c of [...part.connectors].sort((a, b) => a.id - b.id)) writeConnector(w, c);
  w.close("connectors");

  if (part.buses.length) {
    w.open("buses");
    for (const b of part.buses) {
      w.open("bus", [["id", b.id]]);
      for (const id of b.connectorIds) w.empty("nodeMember", [["connectorId", `connector${id}`]]);
      w.close("bus");
    }
    w.close("buses");
  }

  w.close("module");
  return `<?xml version="1.0" encoding="UTF-8"?>\n` + w.toString();
}
